def render_cover(cfg: dict, out: Path, vol: str = "1"):
    try:
        from cover_render import render_cover as _rc, detect_fonts
        fonts = detect_fonts()
        content = {
            "kicker": "RESEARCH COMPILATION 2026",
            "hero": cfg["hero"],
            "summary": cfg["summary"],
            "meta": f"Intelligence Research Atlas - Volume {vol} of 6 - Compiled 2026-10-25",
            "footer": f"ATLAS VOL {vol} / 6",
            "year": "2026",
            "word": "RESEARCH",
        }
        palette = {"primary": "#344c57", "text": "#151718", "muted": "#787f82",
                   "bg": "#ffffff"}
        _rc("02", content, str(out), palette=palette, fonts=fonts)
    except Exception as e:
        print(f"cover engine unavailable ({type(e).__name__}); using fallback cover")
        _fallback_cover(cfg, out, vol)


def merge(cover_pdf: Path, body_pdf: Path, out_pdf: Path, title: str):
    from pypdf import PdfReader, PdfWriter
    writer = PdfWriter()
    writer.append(str(cover_pdf))
    writer.append(str(body_pdf))
    writer.add_metadata({
        "/Title": f"Intelligence Research Atlas - {title}",
        "/Author": "Z.ai",
        "/Creator": "Z.ai",
        "/Subject": "Research compilation: AI, LLMs, neuroscience, mathematics of intelligence",
    })
    with open(out_pdf, "wb") as f:
        writer.write(f)


def main():
    out_dir = ROOT / "pdf"
    out_dir.mkdir(exist_ok=True)
    targets = sys.argv[1:] or (["00"] + list(VOLUMES))

    if "00" in targets or not sys.argv[1:]:
        body = build_volume_00(out_dir)
        cover = out_dir / "_cover.pdf"
        render_cover({
            "hero": "Intelligence Research Atlas",
            "summary": ("The corpus map, the five load-bearing connections across domains, "
                        "and reading paths. Companion to five domain volumes."),
        }, cover, vol="0")
        merge(cover, body, out_dir / "00-overview.pdf", "Overview")
        print("built 00-overview.pdf")

    for domain, cfg in VOLUMES.items():
        if sys.argv[1:] and domain not in sys.argv[1:]:
            continue
        if not (ROOT / domain / "papers.json").exists():
            print(f"SKIP (no papers.json): {domain}")
            continue
        body = build_domain_volume(domain, cfg, out_dir)
        cover = out_dir / "_cover.pdf"
        vol_no = domain.split("_", 1)[0]
        render_cover(cfg, cover, vol=vol_no)
        merge(cover, body, out_dir / cfg["pdf"], cfg.get("title", cfg["hero"]))
        print(f"built {cfg['pdf']}")

    # cleanup intermediates
    for tmp in (out_dir / "_body.pdf", out_dir / "_cover.pdf"):
        tmp.unlink(missing_ok=True)


if __name__ == "__main__":
    main()
