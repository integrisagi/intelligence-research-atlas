CLEAN = {"→": "->", "↔": "<->", "⇒": "=>", "≡": "=" }


def clean(t: str) -> str:
    for k, v in CLEAN.items():
        t = t.replace(k, v)
    t = t.replace(" — ", " - ")  # avoid line-start em-dash flagged by QA
    t = (t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
    return t.strip()


# ── Doc template with TOC support
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bookmark_name"):
            self.notify("TOCEntry", (getattr(flowable, "bookmark_level", 0),
                                     getattr(flowable, "bookmark_text", ""),
                                     self.page,
                                     getattr(flowable, "bookmark_key", "")))


def heading(text, style_key, level=0):
    key = "h_%s" % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/>%s' % (key, clean(text)), S[style_key])
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = re.sub(r"\*\*", "", text)
    p.bookmark_key = key
    return p


def h1_block(text, first_para=None):
    """H1 with orphan prevention; optionally keep with its first paragraph."""
    out = [CondPageBreak(AVAIL_H * 0.15), heading(text, "h1", 0)]
    if first_para is not None:
        return [CondPageBreak(AVAIL_H * 0.15),
                KeepTogether([heading(text, "h1", 0), Paragraph(clean(first_para), S["body"])])]
    return out




# ── Simple flow diagram (vertical chain, low-saturation fills per charts rules)
class ChainDiagram(Flowable):
    def __init__(self, nodes, title):
        super().__init__()
        self.nodes = nodes
        self.title = title
        self.box_h = 26
        self.gap = 16
        self.box_w = min(330, AVAIL_W * 0.72)

    def wrap(self, availWidth, availHeight):
        self.box_w = min(330, availWidth * 0.9)
        h = 26 + 10 + len(self.nodes) * self.box_h + (len(self.nodes) - 1) * self.gap
        self.width = availWidth
        self.height = h
        return availWidth, h

    def draw(self):
        c = self.canv
        top = self.height
        c.setFont("Serif-Bold", 10.5)
        c.setFillColor(TEXT_PRIMARY)
        c.drawCentredString(self.width / 2, top - 12, self.title)
        y = top - 32
        n = len(self.nodes)
        for i, label in enumerate(self.nodes):
            x = (self.width - self.box_w) / 2
            c.setFillColor(CARD_BG)
            c.setStrokeColor(BORDER)
            c.setLineWidth(0.8)
            c.roundRect(x, y - self.box_h, self.box_w, self.box_h, 4, stroke=1, fill=1)
            c.setFillColor(TEXT_PRIMARY)
            c.setFont("Serif", 9.5)
            c.drawCentredString(self.width / 2, y - self.box_h / 2 - 3, clean(label))
            y -= self.box_h
            if i < n - 1:
                c.setStrokeColor(HEADER_FILL)
                c.setLineWidth(1)
                c.line(self.width / 2, y, self.width / 2, y - self.gap + 2)
                c.setFillColor(HEADER_FILL)
                p = c.beginPath()
                p.moveTo(self.width / 2, y - self.gap + 2)
                p.lineTo(self.width / 2 - 3, y - self.gap + 6)
                p.lineTo(self.width / 2 + 3, y - self.gap + 6)
                p.close()
                c.drawPath(p, stroke=0, fill=1)
                y -= self.gap


# ── Content parsing
F_HEAD = re.compile(r"^##\s+(F\d+)\s*[—-]\s*(.+)$")
FIELD = re.compile(r"^\*\*(Claim|Evidence|Why it matters[^*]*)\*\*:?\s*(.*)$")


def parse_findings(path: Path):
    findings = []
    cur = None
    field = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.rstrip()
        m = F_HEAD.match(line)
        if m:
            cur = {"id": m.group(1), "title": m.group(2).strip(), "parts": {}}
            findings.append(cur)
            field = None
            continue
        if cur is None:
            continue
        f = FIELD.match(line)
        if f:
            field = f.group(1).split(":")[0].strip()
            cur["parts"][field] = f.group(2).strip()
        elif line and not line.startswith(("#", "---")) and field:
            cur["parts"][field] += " " + line.strip()
    return findings


def papers_table(papers, chunk=9):
    """Build one or more tables for a paper list. Returns list of flowables."""
    import math
    n_chunks = max(1, math.ceil(len(papers) / chunk))
    chunk = math.ceil(len(papers) / n_chunks)  # balance rows across chunks
    flows = []
    for start in range(0, len(papers), chunk):
        rows = [[
            Paragraph("<b>Year</b>", S["th"]),
            Paragraph("<b>Paper / Authors</b>", S["th"]),
            Paragraph("<b>Core idea</b>", S["th"]),
            Paragraph("<b>Why it matters</b>", S["th"]),
        ]]
        for p in papers[start:start + chunk]:
            rows.append([
                Paragraph(str(p["year"]), S["td"]),
                Paragraph(f"<b>{clean(p['title'])}</b><br/>"
                          f"<font color='#787f82'>{clean(p['authors'])}</font>", S["td"]),
                Paragraph(clean(p.get("core_idea", "")), S["td"]),
                Paragraph(clean(p.get("why_it_matters", "")), S["td"]),
            ])
        ratios = [0.07, 0.31, 0.31, 0.31]
        col_widths = [r * AVAIL_W for r in ratios]
        t = Table(rows, colWidths=col_widths, hAlign="CENTER", repeatRows=1)
        style = [
            ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
            ("LEFTPADDING", (0, 0), (-1, -1), 5),
            ("RIGHTPADDING", (0, 0), (-1, -1), 5),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]
        for i in range(1, len(rows)):
            style.append(("BACKGROUND", (0, i), (-1, i),
                          TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
        t.setStyle(TableStyle(style))
        flows.append(t)
        flows.append(Spacer(1, 10))
    if flows:
        flows.append(Paragraph(
            "Full sources with links live in the corpus: papers.md / papers.json per domain.",
            S["caption"]))
    return flows


